test('coupons, shipping and currency (Super Admin) change what customers can do at checkout', async ({ page, browser }) => {
  await adminLogin(page, creds.superAdmin)
  // a new coupon
  await page.goto('/admin/coupons')
  await page.getByRole('button', { name: 'New coupon' }).click()
  let f = page.getByRole('dialog', { name: 'New coupon' })
  await f.getByLabel('Code').fill('E2E500')
  await f.getByLabel('Type').selectOption('fixed')
  await f.getByLabel('Value').fill('500')
  await f.getByLabel('Minimum purchase (BDT)').fill('1000')
  await f.getByRole('button', { name: 'Save coupon' }).click()
  await expect(page.getByRole('row', { name: /E2E500/ })).toContainText('৳500')

  const cust = await browser.newPage()
  await customerLogin(cust)
  await cust.goto('/product/65w-gan-fast-charger')
  await cust.getByRole('button', { name: 'Add to cart' }).click()
  await cust.goto('/checkout')
  await cust.getByLabel('Coupon code').fill('e2e500')
  await cust.getByRole('button', { name: 'Apply' }).click()
  await expect(cust.locator('aside').getByText('Discount')).toBeVisible()

  // switch Cash on Delivery off for Dhaka: checkout is refused, then back on
  await page.goto('/admin/shipping')
  await page.getByLabel('Edit Dhaka City').click()
  f = page.getByRole('dialog', { name: /Edit shipping zone/ })
  await f.getByLabel('Cash on Delivery available in this zone').uncheck()
  await f.getByRole('button', { name: 'Save shipping zone' }).click()
  await expect(toast(page)).toContainText('saved')
  await cust.reload()
  await expect(cust.getByRole('alert').filter({ hasText: 'Cash on Delivery is not available' })).toBeVisible()
  await expect(cust.getByRole('button', { name: 'Place order' })).toBeDisabled()
  await page.getByLabel('Edit Dhaka City').click()
  f = page.getByRole('dialog', { name: /Edit shipping zone/ })
  await f.getByLabel('Cash on Delivery available in this zone').check()
  await f.getByRole('button', { name: 'Save shipping zone' }).click()
  await cust.reload()
  await expect(cust.getByRole('alert').filter({ hasText: 'Cash on Delivery is not available' })).toHaveCount(0)

  // a rate that is not greater than zero is refused; a new currency appears in the shop
  await page.goto('/admin/currency')
  await page.getByRole('button', { name: 'Add currency' }).click()
  f = page.getByRole('dialog', { name: 'Add currency' })
  await f.getByLabel(/Code/).fill('EUR'); await f.getByLabel('Name').fill('Euro'); await f.getByLabel('Symbol').fill('€'); await f.getByLabel(/Rate/).fill('0')
  await f.getByRole('button', { name: 'Add currency' }).click()
  await expect(f.getByText('Rate must be greater than zero')).toBeVisible()
  await f.getByLabel(/Rate/).fill('0.0076')
  await f.getByRole('button', { name: 'Add currency' }).click()
  await expect(toast(page)).toContainText('Currency added')
  await cust.goto('/')
  await expect(cust.getByLabel('Currency').first().locator('option')).toContainText(['BDT ৳', 'USD $', 'EUR €'].map((s) => s.replace(' ', ' ')).slice(0, 0))
  await expect(cust.getByLabel('Currency').first()).toContainText('EUR')
  await page.getByLabel('EUR rate').fill('0.0080')
  await page.getByLabel('EUR rate').blur()
  await expect(toast(page)).toContainText('Rate saved')
  await cust.close()
})
