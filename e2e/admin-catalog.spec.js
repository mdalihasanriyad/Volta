test('products (admin with the products permission): create, upload guard, edit, cost price hidden', async ({ page }) => {
  await adminLogin(page, creds.admin)
  await page.getByRole('link', { name: 'Products' }).click()
  await expect(page.getByRole('heading', { name: 'Products' })).toBeVisible()
  await page.getByRole('button', { name: 'New product' }).click()
  const form = page.getByRole('dialog', { name: 'New product' })
  await expect(form.getByLabel(/Cost price/)).toHaveCount(0)             // cost prices are Super Admin only
  await form.getByLabel('Name', { exact: true }).fill('E2E Desk Lamp')
  await form.getByLabel('SKU', { exact: true }).fill('E2E-LAMP-1')
  await form.getByLabel('Category', { exact: true }).selectOption({ label: 'Other Gadgets' })
  await form.getByLabel('Price (BDT)').fill('2500')
  await form.getByLabel('Status', { exact: true }).selectOption('active')
  await form.getByLabel('Opening stock').fill('6')
  // image upload is refused politely when Cloudinary is not configured
  await form.locator('input[type=file]').setInputFiles({ name: 'lamp.png', mimeType: 'image/png', buffer: PNG })
  await expect(form.getByRole('alert')).toContainText('not configured')
  await form.getByRole('button', { name: 'Save product' }).click()
  await expect(toast(page)).toContainText('Product created')
  await expect(page.getByRole('row', { name: /E2E Desk Lamp/ })).toContainText('E2E-LAMP-1')
  // visible in the shop because it is active
  const shop = await page.context().newPage()
  await shop.goto('/shop?q=E2E-LAMP')
  await expect(shop.locator('article').first()).toContainText('E2E Desk Lamp')
  await expect(shop.locator('article').first()).toContainText('৳2,500')
  // edit the price
  await page.getByLabel('Edit E2E Desk Lamp').click()
  const edit = page.getByRole('dialog', { name: /Edit E2E Desk Lamp/ })
  await edit.getByLabel('Price (BDT)').fill('2700')
  await edit.getByRole('button', { name: 'Save product' }).click()
  await expect(page.getByRole('row', { name: /E2E Desk Lamp/ })).toContainText('৳2,700')
  await shop.reload()
  await expect(shop.locator('article').first()).toContainText('৳2,700')
  await shop.close()
  // duplicate SKU is refused with a message
  await page.getByRole('button', { name: 'New product' }).click()
  const dup = page.getByRole('dialog', { name: 'New product' })
  await dup.getByLabel('Name', { exact: true }).fill('Copy')
  await dup.getByLabel('SKU', { exact: true }).fill('e2e-lamp-1')
  await dup.getByLabel('Category', { exact: true }).selectOption({ label: 'Other Gadgets' })
  await dup.getByLabel('Price (BDT)').fill('10')
  await dup.getByRole('button', { name: 'Save product' }).click()
  await expect(dup.getByRole('alert')).toContainText('already in use')
  await dup.getByRole('button', { name: 'Cancel' }).click()
})

