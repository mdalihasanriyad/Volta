test('a guest cart is kept and saved on the server after signing in', async ({ page, request }) => {
  await addCharger(page, 2)
  await customerLogin(page)
  await page.waitForTimeout(1200)                      // the cart is saved to the server shortly after it changes
  const server = await (await page.request.get('/api/cart')).json()
  expect(server.items).toHaveLength(1)
  expect(server.items[0].quantity).toBe(2)
  expect(server.items[0].product.name).toContain('GaN')
  await page.goto('/cart')
  await expect(page.getByText('65W GaN Fast Charger')).toBeVisible()
})

test('checkout: live totals, coupon, delivery method, COD confirmation and order creation', async ({ page, request }) => {
  await customerLogin(page)
  await page.goto('/cart')
  await expect(page.getByText('65W GaN Fast Charger')).toBeVisible()
  await page.getByRole('link', { name: 'Proceed to checkout' }).click()
  await expect(page).toHaveURL(/\/checkout/)
  await expect(page.getByText('House 12, Road 5, Dhanmondi')).toBeVisible()       // saved default address pre-selected
  const summary = page.locator('aside')
  await expect(summary.getByText('Delivery', { exact: true })).toBeVisible()
  await expect(summary.getByText('Free')).toBeVisible()                           // 2 x 3,200 is above the free-delivery threshold
  await expect(summary.getByText(/Total \(BDT\)/)).toBeVisible()
  await expect(summary.locator('dd').last()).toHaveText('৳6,400')
  // express costs money
  await page.getByLabel('Express delivery').check()
  await expect(summary.locator('dd').last()).toHaveText('৳6,560')
  await page.getByLabel('Standard delivery').check()
  // coupons
  await page.getByLabel('Coupon code').fill('NOPE')
  await page.getByRole('button', { name: 'Apply' }).click()
  await expect(page.getByText('This coupon is not valid.')).toBeVisible()
  await page.getByLabel('Coupon code').fill('welcome10')
  await page.getByRole('button', { name: 'Apply' }).click()
  await expect(summary.getByText('Discount')).toBeVisible()
  await expect(summary.locator('dd').last()).toHaveText('৳5,760')
  // COD must be confirmed
  await expect(page.getByRole('button', { name: 'Place order' })).toBeDisabled()
  await page.getByLabel(/I confirm that I will pay the total in cash on delivery/).check()
  const before = await stockOf(request, 'GaN')
  await page.getByRole('button', { name: 'Place order' }).click()
  await expect(page.getByRole('heading', { name: 'Order placed' })).toBeVisible()
  await expect(page.getByText(/^VLT-\d+$/)).toBeVisible()
  await expect(page.getByText('Cash on Delivery (unpaid)')).toBeVisible()
  await expect(page.getByText('Pending', { exact: true })).toBeVisible()
  expect(await stockOf(request, 'GaN')).toBe(before - 2)                          // stock was deducted
  const cart = await (await page.request.get('/api/cart')).json()
  expect(cart.items).toHaveLength(0)                                              // saved cart cleared
  await page.goto('/cart')
  await expect(page.getByText('Your cart is empty')).toBeVisible()
})

