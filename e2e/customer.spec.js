  const desktop = await browser.newPage({ viewport: { width: 1366, height: 900 } })
  await desktop.goto('/')
  await expect(desktop.getByRole('navigation', { name: 'Mobile' })).toBeHidden()
  await expect(desktop.locator('footer')).toBeVisible()
  await desktop.getByRole('button', { name: 'All Categories' }).hover()
