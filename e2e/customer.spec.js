import { test, expect, creds, SANDBOX, resetSandbox, lastEmail, customerLogin } from './helpers.js'

test.describe.configure({ mode: 'serial' })
test.beforeAll(async ({ request }) => { await resetSandbox(request) })

const NEW = { name: 'Rafiq Ahmed', email: 'rafiq.e2e@example.test', password: 'Secret123' }

async function addCharger(page, times = 1) {
  await page.goto('/shop?q=GaN')
  await page.getByRole('link', { name: /65W GaN Fast Charger/ }).first().click()
  for (let i = 1; i < times; i++) await page.getByRole('button', { name: 'Increase quantity' }).click()
  await page.getByRole('button', { name: 'Add to cart' }).click()
  await expect(page.getByRole('status')).toContainText('Added to cart')
}
const stockOf = async (request, q) => (await (await request.get(`/api/catalog/products?q=${encodeURIComponent(q)}`)).json()).items[0].stock

test('registration validates input, then sign-up works and checkout waits for email verification', async ({ page, request }) => {
  test.skip(!SANDBOX, 'needs the sandbox email inbox')
  await page.goto('/register')
  await expect(page.getByRole('button', { name: /Google sign-in is not available yet/ })).toBeDisabled()
  await page.getByLabel('Full name').fill(NEW.name)
  await page.getByLabel('Email', { exact: true }).fill(NEW.email)
  await page.getByLabel('Password', { exact: true }).fill('short')
  await page.getByLabel('Confirm password').fill('different')
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByText('Use at least 8 characters')).toBeVisible()
  await expect(page.getByText('Passwords do not match')).toBeVisible()
  await expect(page.getByText('Accept the terms to continue')).toBeVisible()
  await page.getByLabel('Password', { exact: true }).fill(NEW.password)
  await page.getByLabel('Confirm password').fill(NEW.password)
  await page.getByLabel(/I agree to the terms/).check()
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page).toHaveURL(/\/account/)
  await expect(page.getByText('Not verified')).toBeVisible()

  // duplicate email is refused with a clear message
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.goto('/register')
  await page.getByLabel('Full name').fill('Someone Else')
  await page.getByLabel('Email', { exact: true }).fill(NEW.email)
  await page.getByLabel('Password', { exact: true }).fill(NEW.password)
  await page.getByLabel('Confirm password').fill(NEW.password)
  await page.getByLabel(/I agree to the terms/).check()
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('alert')).toContainText('already exists')

  // unverified customers cannot place orders
  await page.goto('/login')
  await page.getByLabel('Email').fill(NEW.email)
  await page.getByLabel('Password').fill(NEW.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await addCharger(page)
  await page.goto('/checkout')
  await expect(page.getByText(/Verify your email address to place orders/)).toBeVisible()

  // verify through the emailed link
  const mail = await lastEmail(request, NEW.email, 'Verify')
  await page.goto(mail.link)
  await expect(page.getByRole('heading', { name: 'Email verified' })).toBeVisible()
  await page.goto('/account')
  await expect(page.getByText('Verified', { exact: true })).toBeVisible()
})

