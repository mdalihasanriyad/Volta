test('currency selector shows prices in USD and checkout records BDT', async ({ page }) => {
  await customerLogin(page)
  await page.goto('/shop?q=GaN')
  await expect(page.locator('article').first()).toContainText('৳3,200')
  await page.getByLabel('Currency').first().selectOption('USD')
  await expect(page.locator('article').first()).toContainText('$26.24')               // 3200 x 0.0082
  await page.goto('/product/65w-gan-fast-charger')
  await page.getByRole('button', { name: 'Add to cart' }).click()
  await page.goto('/checkout')
  const note = page.getByText(/recorded as ৳[\d,]+ at 1 BDT = 0.0082 USD/)
  await expect(note).toBeVisible()
  const bdt = Number((await note.textContent()).match(/৳([\d,]+)/)[1].replace(/,/g, ''))
  await expect(page.locator('aside dd').last()).toHaveText(`$${(bdt * 0.0082).toFixed(2)}`)   // the USD total is the BDT total at the shop's rate
  await page.getByLabel('Currency').first().selectOption('BDT')
})

test('account: orders can be cancelled while pending and stock is restored; tracking is public', async ({ page, browser, request }) => {
  await customerLogin(page)
  await page.goto('/account?tab=orders')
  const card = page.locator('li').filter({ hasText: /^VLT-/ }).first()
  await expect(card).toContainText('Pending')
  const number = (await card.locator('p.font-bold').first().textContent()).trim()
  const before = await stockOf(request, 'GaN')
  page.once('dialog', (d) => d.accept())
  await card.getByRole('button', { name: 'Cancel order' }).click()
  await expect(card).toContainText('Cancelled')
  expect(await stockOf(request, 'GaN')).toBe(before + 2)
  // anyone with the number + email can track it, nobody else
  const guest = await browser.newPage()
  await guest.goto(`/order-tracking?order=${number}`)
  await guest.getByPlaceholder(/Email or phone/).fill('wrong@example.test')
  await guest.getByRole('button', { name: 'Track' }).click()
  await expect(guest.getByText(/could not find an order/i)).toBeVisible()
  await guest.getByPlaceholder(/Email or phone/).fill(creds.customer.email)
  await guest.getByRole('button', { name: 'Track' }).click()
  await expect(guest.getByText('Cancelled').first()).toBeVisible()
  await guest.close()
})

